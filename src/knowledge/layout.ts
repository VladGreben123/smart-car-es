import { QUESTIONS, type ScenarioName, type Question } from "./questions";

/** Один вопрос с привязкой к сценарию-владельцу. */
export type FlatQuestion = {
  scenario: ScenarioName;
  question: Question;
  /** Уникальный ID элемента в общей зоне */
  uid: string;
};

/**
 * Плоский список всех вопросов из всех сценариев, упорядоченный по смыслу.
 *
 * Группировка существует только в порядке элементов:
 *   1. Идентификация ситуации (тип ситуации, тип перекрёстка, намерение манёвра).
 *   2. Знаки и правила приоритета.
 *   3. Участники движения (пешеход, ТС на главной, целевая полоса).
 *   4. Дистанции и скорость.
 *
 * Визуально границы между группами не отображаются — это просто
 * последовательность вопросов в общей зоне.
 */
function ordered(scenario: ScenarioName, keys: string[]): FlatQuestion[] {
  const result: FlatQuestion[] = [];
  for (const key of keys) {
    const q = QUESTIONS[scenario].find((x) => x.key === key);
    if (!q) continue;
    result.push({ scenario, question: q, uid: `${scenario}::${q.key}` });
  }
  return result;
}

